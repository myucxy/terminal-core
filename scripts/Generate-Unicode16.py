"""Generate deterministic property tables from checked-in Unicode 16.0.0 data.

No network or package dependencies. Source files retain Unicode License V3.
"""
import hashlib
import json
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "third_party/unicode/16.0.0"
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]


def records(name):
    for line in (SOURCE / name).read_text(encoding="utf-8").splitlines():
        text = line.partition("#")[0].strip()
        if not text:
            continue
        fields = [field.strip() for field in text.split(";")]
        bounds = fields[0].split("..")
        yield int(bounds[0], 16), int(bounds[-1], 16), fields[1:]


def merged(rows):
    result = []
    for start, end, prop in sorted(rows):
        if result and start <= result[-1][1]:
            raise ValueError("overlapping Unicode ranges")
        if result and start == result[-1][1] + 1 and prop == result[-1][2]:
            result[-1] = (result[-1][0], end, prop)
        else:
            result.append((start, end, prop))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated tables without writing")
    args = parser.parse_args()
    for item in json.loads((SOURCE / "SHA256.json").read_text(encoding="utf-8")):
        actual = hashlib.sha256((SOURCE / item["file"]).read_bytes()).hexdigest()
        if actual != item["sha256"]:
            raise ValueError("Unicode source hash mismatch: " + item["file"])
    tables = {
        "GRAPHEME_BREAK": [(a, b, GCB.index(p[0])) for a, b, p in records("GraphemeBreakProperty.txt")],
        "INDIC_CONJUNCT_BREAK": [(a, b, ["None", "Consonant", "Extend", "Linker"].index(p[1])) for a, b, p in records("DerivedCoreProperties.txt") if p[0] == "InCB"],
        "DEFAULT_IGNORABLE": [(a, b, 1) for a, b, p in records("DerivedCoreProperties.txt") if p[0] == "Default_Ignorable_Code_Point"],
        "WIDE": [(a, b, 1) for a, b, p in records("EastAsianWidth.txt") if p[0] in ("W", "F")],
    }
    for name in ["Extended_Pictographic", "Emoji_Presentation", "Emoji"]:
        tables[name.upper()] = [(a, b, 1) for a, b, p in records("emoji-data.txt") if p[0] == name]
    lines = ["// Generated by scripts/Generate-Unicode16.py. Do not edit.",
             "// Unicode 16.0.0 data: Copyright Unicode, Inc. Unicode License V3.",
             "// Full source, hashes and license: third_party/unicode/16.0.0/.", ""]
    for name, values in tables.items():
        lines.append("pub(super) const " + name + ": &[(u32, u32, u8)] = &[")
        for start, end, value in merged(values):
            lines.append(f"    (0x{start:X}, 0x{end:X}, {value}),")
        lines.extend(["];", ""])
    target = ROOT / "crates/termlink-terminal-core/src/unicode16_data.rs"
    generated = "\n".join(lines)
    if args.check:
        if target.read_text(encoding="utf-8") != generated:
            raise ValueError("Unicode tables are stale; run scripts/Generate-Unicode16.py")
        print("Unicode 16 source hashes and generated tables verified")
    else:
        target.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
