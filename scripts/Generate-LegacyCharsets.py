"""Generate fixed mapping constants; no network or host locale is used."""
from pathlib import Path
import json
import argparse

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if the checked-in data is stale.')
args = parser.parse_args()

root = Path(__file__).resolve().parents[1]
tables = json.loads((root / 'third_party/legacy-charsets/tables.json').read_text(encoding='utf-8'))
assert len(tables) == 16
lines = ['// Generated by scripts/Generate-LegacyCharsets.py. Do not edit.',
         '// Mapping data Copyright (c) Microsoft Corporation, MIT.',
         '// See third_party/legacy-charsets for source, pinned revision and license.',
         'pub(super) const DESCRIPTORS: [(&str, bool, bool); 16] = [']
for table in tables:
    assert table['size'] in (94, 96) and len(table['scalars']) == 96
    lines.append('    (' + json.dumps(table['designator']) + ', ' +
                 str(table['size'] == 96).lower() + ', ' + str(table['national']).lower() + '),')
lines += ['];', '#[rustfmt::skip]', 'pub(super) const TABLES: [[char; 96]; 16] = [']
for table in tables:
    lines += ['    [', '        // ' + table['name']]
    for offset in range(0, 96, 8):
        values = table['scalars'][offset:offset+8]
        assert all(0 <= v <= 0x10ffff and not 0xd800 <= v <= 0xdfff for v in values)
        lines.append('        ' + ', '.join("'\\u{" + f'{v:x}' + "}'" for v in values) + ',')
    lines.append('    ],')
lines += ['];', '']
target = root / 'crates/termlink-terminal-core/src/legacy_charset_data.rs'
generated = '\n'.join(lines)
if args.check:
    if target.read_text(encoding='utf-8') != generated:
        raise SystemExit('Legacy charset data is stale. Run scripts/Generate-LegacyCharsets.py.')
    print('Legacy charset generation is reproducible (16 tables).')
else:
    target.write_text(generated, encoding='utf-8')
